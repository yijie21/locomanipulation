"""The 25.5 perturbation cells, SONIC side (TODO 25.5, plan §4.6): one experiment yaml per (task, perturbation), written
from the L1 production configs (bottle: seeds 40000.., recorded for the pose sidecar; warehouse: seeds 7000.., state
trace only), ten rounds each. The perturbation goes to the sim through collect.stack_env LOCOMANI_PERTURB
(src/locomani/sim/perturb.py); payload (e) swaps the scene for payload_scenes.py's copy. The same specs drive the
ScaleBFM side (bfm_expert_*.py --perturb, runtime.Sim(perturb=...)).

    python3 scripts/experiments/controller_compare_20261013/perturb_configs.py   # -> configs/experiments/controller_compare_p25_*_20261013.yaml
"""

from __future__ import annotations

import json
import re
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
NOISE = {"gyro": 0.1, "dq": 0.5}
CELLS = {
    "b20": {"delay_s": 0.02},
    "b40": {"delay_s": 0.04},
    "c": {"noise": NOISE, "seed": 25},
    "d04": {"friction": 0.4},
    "f": {"gain_scale": [0.8, 1.2], "seed": 25},
    "g": {"push_every_s": 3.0, "push_n": [50.0, 100.0], "push_s": 0.2, "seed": 25},
}
PAYLOAD = {"e050": 0.5, "e150": 1.5}
TASKS = {
    # task: (base config, scene key line, payload scene base, cells)
    "bottle": (
        "controller_compare_bottle_sonic_20261013.yaml",
        "outputs/scene/sim_lowcom",
        ("b20", "b40", "c", "d04", "f", "e050", "e150"),
    ),
    "warehouse": (
        "controller_compare_warehouse_sonic_20261013.yaml",
        "outputs/scene/warehouse_box_45x32x33_mars",
        ("b20", "b40", "c", "d04", "f", "e050", "e150"),
    ),
}


def spec_json(cell: str) -> str:
    return json.dumps(CELLS[cell], separators=(",", ":"))


def write(task: str, cell: str) -> Path:
    base, scene, _ = TASKS[task]
    src = (REPO / "configs" / "experiments" / base).read_text()
    lines = src.split("\n")
    i = next(k for k, line in enumerate(lines) if line.startswith("name:"))
    body = "\n".join(lines[i:])
    name = f"controller_compare_p25_{task}_{cell}_20261013"
    body = re.sub(r"^name: .*$", f"name: {name}", body, count=1, flags=re.M)
    what = f"payload x{PAYLOAD[cell]}" if cell in PAYLOAD else f"LOCOMANI_PERTURB={spec_json(cell)}"
    if cell in PAYLOAD:
        new_scene = f"{scene}_m{round(100 * PAYLOAD[cell]):03d}"
        if task == "bottle":
            body, n = re.subn(r"^  dir: outputs/scene/sim_lowcom$", f"  dir: {new_scene}", body, count=1, flags=re.M)
        else:
            body, n = re.subn(
                r"^  name: warehouse_box_45x32x33_mars$", f"  dir: {new_scene}", body, count=1, flags=re.M
            )
            body, n2 = re.subn(r"^  source: unreal$", "  source: mujoco", body, count=1, flags=re.M)
            body, n3 = re.subn(r"^    render: offline\n", "", body, count=1, flags=re.M)
            assert n2 == 1 and n3 == 1, "warehouse images / render lines"
        assert n == 1, "scene line"
    else:
        body, n = re.subn(
            r"^  stack_env: .*$", f"  stack_env: ['LOCOMANI_PERTURB={spec_json(cell)}']", body, count=1, flags=re.M
        )
        assert n == 1, "stack_env line"
    header = (
        f"# TODO 25.5 perturbation {cell} ({what}), {task} L1 production tier, SONIC side (plan §4.6;\n"
        f"# docs/handoff/controller-compare-20261013.md): {base} verbatim except the name and this perturbation.\n"
        "# Generated by scripts/experiments/controller_compare_20261013/perturb_configs.py. Instance 0, nothing else running.\n"
    )
    out = REPO / "configs" / "experiments" / f"{name}.yaml"
    out.write_text(header + body)
    return out


def main() -> int:
    for task, (_, _, cells) in TASKS.items():
        for cell in cells:
            print(write(task, cell).relative_to(REPO))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
