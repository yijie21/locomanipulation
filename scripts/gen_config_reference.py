#!/usr/bin/env python3
"""Generate docs/reference/config_fields.md from the config dataclasses (decision 8).

One table per config: field, default, comment (the field's own trailing `#
comment`, copied verbatim -- the source of truth stays the dataclass, this is
a projection of it, never hand-edited).

    python scripts/gen_config_reference.py          # regenerate
    python scripts/gen_config_reference.py --check   # exit 1 if the file on disk is stale
"""

import dataclasses
import inspect
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "src"))

from locomani.backends.scalebfm.config import ScaleBfmBackendConfig  # noqa: E402
from locomani.backends.sonic.config import LockstepConfig, SonicBackendConfig  # noqa: E402
from locomani.pipeline.eval_config import EvalConfig  # noqa: E402
from locomani.tasks.bottle.config import BottleTaskConfig, SpawnConfig  # noqa: E402
from locomani.tasks.bottle.image_servo_config import BottleCalibration, ServoLimits  # noqa: E402
from locomani.tasks.bottle.reach_config import ReachConfig  # noqa: E402
from locomani.tasks.bottle.simple_config import SimpleGraspConfig  # noqa: E402
from locomani.tasks.bottle.whole_body_config import WholeBodyConfig  # noqa: E402
from locomani.tasks.bottle_visual.config import BottleVisualTaskConfig, GraspConfig  # noqa: E402
from locomani.tasks.crate.carry_config import CrateCarryConfig  # noqa: E402
from locomani.tasks.crate.config import CrateTaskConfig  # noqa: E402
from locomani.tasks.crate.visual_config import CrateVisualConfig  # noqa: E402

# (heading, dataclass, source module docstring's one-line summary)
CONFIGS = [
    ("SonicBackendConfig", SonicBackendConfig, "locomani/backends/sonic/config.py"),
    ("LockstepConfig", LockstepConfig, "locomani/backends/sonic/config.py (SonicBackendConfig.lockstep)"),
    ("BottleTaskConfig", BottleTaskConfig, "locomani/tasks/bottle/config.py"),
    ("SpawnConfig", SpawnConfig, "locomani/tasks/bottle/config.py (BottleTaskConfig.spawn)"),
    ("ReachConfig", ReachConfig, "locomani/tasks/bottle/reach_config.py (BottleTaskConfig.reach)"),
    (
        "BottleCalibration",
        BottleCalibration,
        "locomani/tasks/bottle/image_servo_config.py (ReachConfig.image_calibration)",
    ),
    ("ServoLimits", ServoLimits, "locomani/tasks/bottle/image_servo_config.py (ReachConfig.image_control)"),
    ("WholeBodyConfig", WholeBodyConfig, "locomani/tasks/bottle/whole_body_config.py (ReachConfig.whole_body)"),
    ("SimpleGraspConfig", SimpleGraspConfig, "locomani/tasks/bottle/simple_config.py (ReachConfig.simple)"),
    ("CrateTaskConfig", CrateTaskConfig, "locomani/tasks/crate/config.py"),
    ("CrateCarryConfig", CrateCarryConfig, "locomani/tasks/crate/carry_config.py (CrateTaskConfig.carry)"),
    ("CrateVisualConfig", CrateVisualConfig, "locomani/tasks/crate/visual_config.py (CrateTaskConfig.visual)"),
    ("ScaleBfmBackendConfig", ScaleBfmBackendConfig, "locomani/backends/scalebfm/config.py"),
    ("BottleVisualTaskConfig", BottleVisualTaskConfig, "locomani/tasks/bottle_visual/config.py"),
    ("GraspConfig", GraspConfig, "locomani/tasks/bottle_visual/config.py (BottleVisualTaskConfig.grasp)"),
    ("EvalConfig", EvalConfig, "locomani/pipeline/eval_config.py"),
]

FIELD_RE = re.compile(r"^\s*([A-Za-z_][A-Za-z0-9_]*)\s*:")


def _field_comments(cls) -> dict:
    """field name -> its trailing `# comment` (from the class source), or ""."""
    comments = {}
    name = None
    for line in inspect.getsource(cls).splitlines():
        m = FIELD_RE.match(line)
        if m:
            name = m.group(1)
            comments[name] = ""
        # a `field(...)` default that ruff wrapped keeps its comment on the closing `)  # ...` line
        if name and "#" in line and not comments[name] and not line.strip().startswith("#"):
            comments[name] = line.split("#", 1)[1].strip()
    return comments


def _default_repr(f: dataclasses.Field) -> str:
    if f.default is not dataclasses.MISSING:
        return repr(f.default)
    if f.default_factory is not dataclasses.MISSING:  # nested dataclass
        return f"{f.default_factory.__name__}()"
    return "(required)"


def render_table(cls) -> str:
    comments = _field_comments(cls)
    rows = ["| field | default | comment |", "|---|---|---|"]
    for f in dataclasses.fields(cls):
        default = _default_repr(f).replace("|", "\\|")
        comment = comments.get(f.name, "").replace("|", "\\|")
        if f.metadata.get("choices"):
            comment = (comment + " " if comment else "") + "choices: " + " / ".join(map(str, f.metadata["choices"]))
        rows.append(f"| `{f.name}` | `{default}` | {comment} |")
    return "\n".join(rows)


def render() -> str:
    parts = [
        "# Config field reference",
        "",
        "Generated by `scripts/gen_config_reference.py` from the dataclasses themselves "
        "(decision 8, refactor step 3) -- do not hand-edit; run `make config-doc` after "
        "changing a config module.",
        "",
    ]
    for heading, cls, source in CONFIGS:
        parts.append(f"## {heading}")
        parts.append("")
        parts.append(f"`{source}`")
        parts.append("")
        parts.append(render_table(cls))
        parts.append("")
    return "\n".join(parts).rstrip() + "\n"


def main() -> None:
    out = REPO / "docs/reference/config_fields.md"
    content = render()
    if "--check" in sys.argv:
        current = out.read_text() if out.exists() else ""
        if current != content:
            print(f"[gen_config_reference] {out} is stale; run `make config-doc`", file=sys.stderr)
            sys.exit(1)
        print(f"[gen_config_reference] {out} is up to date")
        return
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(content)
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
